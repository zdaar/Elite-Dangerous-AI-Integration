# Frontier's journal appendix calls these the main-sequence star classes.  The
# warning feature intentionally uses the user's exact KGBFOAM definition: only
# these seven complete class codes are treated as KGBFOAM.
KGBFOAM_CLASSES = frozenset({"K", "G", "B", "F", "O", "A", "M"})


@dataclass(frozen=True)
class StarClassProfile:
    canonical_class: str
    normalized_class: str
    family: str
    family_en: str
    family_fr: str
    scoopable: bool | None
    appearance_en: str
    appearance_fr: str
    arrival_hazard_en: str
    arrival_hazard_fr: str
    jet_cone_supercharging: bool | None
    recommended_action_en: str
    recommended_action_fr: str


def _profile(
    canonical_class: str,
    *,
    family: str,
    family_en: str,
    family_fr: str,
    scoopable: bool | None,
    appearance_en: str,
    appearance_fr: str,
    arrival_hazard_en: str,
    arrival_hazard_fr: str,
    jet_cone_supercharging: bool | None,
    recommended_action_en: str,
    recommended_action_fr: str,
) -> StarClassProfile:
    return StarClassProfile(
        canonical_class=canonical_class,
        normalized_class=canonical_class.upper(),
        family=family,
        family_en=family_en,
        family_fr=family_fr,
        scoopable=scoopable,
        appearance_en=appearance_en,
        appearance_fr=appearance_fr,
        arrival_hazard_en=arrival_hazard_en,
        arrival_hazard_fr=arrival_hazard_fr,
        jet_cone_supercharging=jet_cone_supercharging,
        recommended_action_en=recommended_action_en,
        recommended_action_fr=recommended_action_fr,
    )


def _family_profiles(
    classes: tuple[str, ...],
    **kwargs: object,
) -> dict[str, StarClassProfile]:
    profiles: dict[str, StarClassProfile] = {}
    for star_class in classes:
        profile = _profile(star_class, **kwargs)  # type: ignore[arg-type]
        profiles[profile.normalized_class] = profile
    return profiles


