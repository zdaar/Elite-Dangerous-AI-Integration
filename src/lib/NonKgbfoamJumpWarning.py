def configured_warning_language(config: dict[str, object]) -> Literal["en", "fr"]:
    language_values: list[object] = []
    characters = config.get("characters")
    active_index = config.get("active_character_index", 0)
    if isinstance(characters, list) and isinstance(active_index, int):
        if 0 <= active_index < len(characters) and isinstance(characters[active_index], dict):
            language_values.append(characters[active_index].get("personality_language"))
    language_values.append(config.get("tts_language"))
    for value in language_values:
        if not isinstance(value, str):
            continue
        normalized = value.strip().casefold()
        if normalized.startswith("fr") or "french" in normalized or "français" in normalized or "francais" in normalized:
            return "fr"
    return "en"


@dataclass(frozen=True)
class JumpTarget:
    name: str | None
    system_address: int | None
    star_class: object


@dataclass(frozen=True)
class JumpWarningDecision:
    cycle_id: int
    kind: Literal["known", "unknown"]
    trigger: Literal["fsd_charging", "start_jump"]
    target_name: str | None
    star_class: str | None
    profile: StarClassProfile | None


class NonKgbfoamJumpWarningController:
    """Pure local state machine for one warning per hyperspace charge cycle."""

    def __init__(self) -> None:
        self.current_target: JumpTarget | None = None
        self.charge_active = False
        self.charge_kind: Literal["hyperspace", "supercruise", "unknown"] | None = None
        self.cycle_sequence = 0
        self.active_cycle_id: int | None = None
        self.cycle_warned = False
        self.phase: Literal["idle", "charging", "countdown", "completed"] = "idle"

    @staticmethod
    def _address(value: object) -> int | None:
        return value if isinstance(value, int) and not isinstance(value, bool) else None

    @staticmethod
    def _name(value: object) -> str | None:
        if not isinstance(value, str):
            return None
        value = value.strip()
        return value or None

    def _begin_cycle(
        self,
        kind: Literal["hyperspace", "supercruise", "unknown"],
    ) -> None:
        self.cycle_sequence += 1
        self.active_cycle_id = self.cycle_sequence
        self.cycle_warned = False
        self.charge_kind = kind
        self.phase = "charging"

    def _target_for_status(self, status: dict[str, object]) -> JumpTarget | None:
        target = self.current_target
        destination = status.get("Destination")
        if not isinstance(destination, dict):
            return target

        destination_address = self._address(destination.get("System"))
        destination_name = self._name(destination.get("Name"))
        if target is None:
            return JumpTarget(destination_name, destination_address, None)

        address_mismatch = (
            destination_address is not None
            and target.system_address is not None
            and destination_address != target.system_address
        )
        name_mismatch = (
            destination_name is not None
            and target.name is not None
            and destination_name.casefold() != target.name.casefold()
        )
        if address_mismatch or (target.system_address is None and name_mismatch):
            # The cached FSDTarget is stale.  Preserve destination identity but
            # never carry its class over to a different target.
            return JumpTarget(destination_name, destination_address, None)
        return target

    def _decision_for_target(
        self,
        target: JumpTarget | None,
        *,
        trigger: Literal["fsd_charging", "start_jump"],
        warning_enabled: bool,
        unknown_warning_enabled: bool,
    ) -> JumpWarningDecision | None:
        if self.active_cycle_id is None or self.cycle_warned or not warning_enabled:
            return None

        star_class = normalize_star_class(target.star_class) if target else None
        if star_class in KGBFOAM_CLASSES:
            return None

        profile = get_star_class_profile(star_class)
        if profile is not None:
            self.cycle_warned = True
            return JumpWarningDecision(
                cycle_id=self.active_cycle_id,
                kind="known",
                trigger=trigger,
                target_name=target.name if target else None,
                star_class=profile.canonical_class,
                profile=profile,
            )

        if not unknown_warning_enabled:
            return None
        self.cycle_warned = True
        return JumpWarningDecision(
            cycle_id=self.active_cycle_id,
            kind="unknown",
            trigger=trigger,
            target_name=target.name if target else None,
            star_class=star_class,
            profile=None,
        )

    def process(
        self,
        event: Event,
        *,
        warning_enabled: bool,
        unknown_warning_enabled: bool,
    ) -> JumpWarningDecision | None:
        if isinstance(event, GameEvent):
            event_name = event.content.get("event")
            if event_name == "FSDTarget":
                self.current_target = JumpTarget(
                    name=self._name(event.content.get("Name")),
                    system_address=self._address(event.content.get("SystemAddress")),
                    star_class=event.content.get("StarClass"),
                )
                return None

            if event_name == "StartJump":
                if event.content.get("JumpType") != "Hyperspace":
                    self.phase = "countdown"
                    self.charge_kind = "supercruise"
                    return None
                if self.active_cycle_id is None:
                    self._begin_cycle("hyperspace")
                self.phase = "countdown"
                self.charge_kind = "hyperspace"
                start_target = JumpTarget(
                    name=self._name(event.content.get("StarSystem")),
                    system_address=self._address(event.content.get("SystemAddress")),
                    star_class=event.content.get("StarClass"),
                )
                return self._decision_for_target(
                    start_target,
                    trigger="start_jump",
                    warning_enabled=warning_enabled,
                    unknown_warning_enabled=unknown_warning_enabled,
                )

            if event_name == "FSDJump":
                self.charge_active = False
                self.charge_kind = None
                self.active_cycle_id = None
                self.cycle_warned = False
                self.phase = "completed"
                return None

            if event_name in {"LoadGame", "Shutdown"}:
                self.current_target = None
                self.charge_active = False
                self.charge_kind = None
                self.active_cycle_id = None
                self.cycle_warned = False
                self.phase = "idle"
                return None

            # NavRoute and NavRouteClear intentionally have no warning side
            # effects.  FSDTarget remains authoritative for a selected hop.
            return None

        if not isinstance(event, StatusEvent):
            return None

        event_name = event.status.get("event")
        if event_name == "Status":
            flags = event.status.get("flags")
            if not isinstance(flags, dict):
                return None
            is_charging = bool(flags.get("FsdCharging"))
            if not is_charging:
                self.charge_active = False
                if self.phase == "charging":
                    self.phase = "idle"
                return None
            if self.charge_active:
                return None

            self.charge_active = True
            flags2 = event.status.get("flags2")
            hyperdrive_flag: bool | None = None
            if isinstance(flags2, dict) and "FsdHyperdriveCharging" in flags2:
                hyperdrive_flag = bool(flags2.get("FsdHyperdriveCharging"))
            kind: Literal["hyperspace", "supercruise", "unknown"] = (
                "hyperspace" if hyperdrive_flag is True
                else "supercruise" if hyperdrive_flag is False
                else "unknown"
            )
            self._begin_cycle(kind)
            if kind != "hyperspace":
                return None
            return self._decision_for_target(
                self._target_for_status(event.status),
                trigger="fsd_charging",
                warning_enabled=warning_enabled,
                unknown_warning_enabled=unknown_warning_enabled,
            )

        if event_name == "FsdCharging":
            if self.charge_active:
                return None
            self.charge_active = True
            jump_type = event.status.get("JumpType")
            kind = (
                "hyperspace" if jump_type == "Hyperspace"
                else "supercruise" if jump_type == "Supercruise"
                else "unknown"
            )
            self._begin_cycle(kind)
            if kind != "hyperspace":
                return None
            return self._decision_for_target(
                self.current_target,
                trigger="fsd_charging",
                warning_enabled=warning_enabled,
                unknown_warning_enabled=unknown_warning_enabled,
            )

        return None
