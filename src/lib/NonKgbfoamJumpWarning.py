def normalize_star_class(value: object) -> str | None:
    if not isinstance(value, str):
        return None
    normalized = value.strip().upper()
    return normalized or None


def is_kgbfoam(value: object) -> bool:
    normalized = normalize_star_class(value)
    return normalized in KGBFOAM_CLASSES if normalized else False


def get_star_class_profile(value: object) -> StarClassProfile | None:
    normalized = normalize_star_class(value)
    if normalized is None:
        return None
    return STAR_CLASS_PROFILES.get(normalized)


def _fuel_hazard(language: Literal["en", "fr"]) -> str:
    if language == "fr":
        return "Risque réel de panne sèche si aucune étoile scoopable ne reste à portée."
    return "There is a real fuel-stranding risk if no scoopable star remains within range."


def format_star_warning(
    profile: StarClassProfile,
    language: Literal["en", "fr"],
) -> str:
    if language == "fr":
        if profile.scoopable is True:
            scoopability = "Scoopable malgré son code hors des sept classes KGBFOAM exactes."
        elif profile.scoopable is False:
            scoopability = f"Non scoopable. {_fuel_hazard('fr')}"
        else:
            scoopability = "Scoopabilité non documentée."
        jet = (
            " Surcharge par cône possible ; manœuvre à n'entreprendre que volontairement."
            if profile.jet_cone_supercharging is True
            else ""
        )
        return (
            f"Attention calme : prochaine étoile, {profile.family_fr}, code journal {profile.canonical_class}. "
            f"{scoopability} Aspect attendu : {profile.appearance_fr} ; {profile.arrival_hazard_fr}."
            f"{jet} {profile.recommended_action_fr}"
        )

    if profile.scoopable is True:
        scoopability = "It is scoopable despite being outside the seven exact KGBFOAM codes."
    elif profile.scoopable is False:
        scoopability = f"It is not scoopable. {_fuel_hazard('en')}"
    else:
        scoopability = "Its scoopability is not documented."
    jet = (
        " Jet-cone supercharging is possible and should be attempted only deliberately."
        if profile.jet_cone_supercharging is True
        else ""
    )
    return (
        f"Calm warning: next star, {profile.family_en}, journal code {profile.canonical_class}. "
        f"{scoopability} Expected appearance: {profile.appearance_en}; {profile.arrival_hazard_en}."
        f"{jet} {profile.recommended_action_en}"
    )


